# ============================================================================
# REMFMT - Remaining Months Format
# ============================================================================
def get_remfmt(remmth: Optional[float]) -> str:
    """Format remaining months into BNM codes"""
    if remmth is None:
        return '07'
    elif remmth <= 0.1:
        return '01'
    elif remmth <= 1:
        return '02'
    elif remmth <= 3:
        return '03'
    elif remmth <= 6:
        return '04'
    elif remmth <= 12:
        return '05'
    else:
        return '06'


